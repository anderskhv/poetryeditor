/** Get frequency tier for display */
export function getFrequencyTier(word: string): 'common' | 'uncommon' | 'rare' {
  const rank = wordFrequencyRank[word.toLowerCase()];
  if (!rank) return 'rare';
  if (rank <= 500) return 'common';
  return 'uncommon';
}

/** Get numeric rank (lower = more common). Returns Infinity for unknown words */
export function getFrequencyRank(word: string): number {
  return wordFrequencyRank[word.toLowerCase()] ?? Infinity;
}
